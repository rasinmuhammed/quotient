LEGAL_SUFFIXES = {"inc", "llc", "gmbh", "fze", "co", "ltd", "ltda", "bv"}
EMAIL_TLD = {"US": "com", "DE": "de", "AE": "ae", "JP": "co.jp", "BR": "com.br", "NL": "nl"}


def _ascii(s: str) -> str:
    import unicodedata

    return unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode()


def business_email(person: str, company: str, country_code: str) -> str:
    """first.last@companydomain.tld: a derivation of two generated values, not a draw (B2B buyers write from work addresses)."""
    words = [w for w in _ascii(company).lower().replace(",", " ").replace(".", " ").split() if w not in LEGAL_SUFFIXES]
    local = ".".join(_ascii(person).lower().split()[:1] + _ascii(person).lower().split()[-1:])
    return f"{local}@{''.join(words)}.{EMAIL_TLD[country_code]}"


def shape(t: dict[str, pd.DataFrame]) -> dict[str, pd.DataFrame]:
    """Join the engine's normalised tables into the flat files the app reads. No value is drawn here."""
    chem = t["chemicals"].set_index("chemical_id")
    grades = t["grades"].set_index("grade")
    packs = t["packs"].set_index("pack_id")
    skus = t["skus"].copy()
    sku_packs = t["sku_packs"].merge(packs[["pack_code"]], left_on="pack_id", right_index=True)
    sku_code = skus.set_index("sku_id")["sku_code"]
    offered = sku_packs.groupby("sku_id")["pack_code"].agg("|".join)

    c = chem.loc[skus["chemical_id"].astype(int)].reset_index(drop=True)
    products = pd.DataFrame(
        {
            "sku": skus["sku_code"],
            "name": skus["sku_name"],
            "chemical_code": c["code"],
            "chemical_name": c["chem_name"],
            "cas": c["cas"],
            "grade": skus["grade"],
            "grade_label": grades.loc[skus["grade"], "label"].to_numpy(),
            "purity_pct": skus["purity_pct"],
            "form": c["form"],
            "uom": skus["uom"],
            "density_kg_per_l": c["density"],
            "hs_code": c["hs_code"],
            "un_number": c["un_number"],
            "hazard_class": c["hazard_class"],
            "moq": skus["moq"].astype(int),
            "lead_time_days": skus["lead_time_days"].astype(int),
            "origin_port": skus["origin_port"],
            "standard_cost_usd": skus["standard_cost"],
            "pack_codes": skus["sku_id"].map(offered),
            "synonyms": c["synonyms"],
            "trade_names": c["trade_names"].fillna(""),
        }
    )

    tiers = t["price_tiers"].merge(sku_packs, on="sku_pack_id").sort_values(["sku_pack_id", "tier_no"])
    nxt = tiers.groupby("sku_pack_id")["min_qty"].shift(-1)
    price_list = pd.DataFrame(
        {
            "price_row_id": tiers["price_tier_id"].map(lambda i: f"PL-{int(i):05d}"),
            "sku": tiers["sku_id"].astype(int).map(sku_code),
            "pack_code": tiers["pack_code"],
            "currency": "USD",
            "uom": tiers["sku_id"].astype(int).map(skus.set_index("sku_id")["uom"]),
            "tier": tiers["tier_no"].astype(int),
            "min_qty": tiers["min_qty"].astype(int),
            "max_qty": nxt.astype("Int64"),  # exclusive; empty on the top tier
            "unit_price": tiers["unit_price"],
            "valid_from": pd.to_datetime(tiers["valid_from"]).dt.date,
            "valid_to": pd.to_datetime(tiers["valid_to"]).dt.date,
        }
    )

    cust = t["customers"].copy()
    code_of = {n: v[0] for n, v in COUNTRIES.items()}
    cust["country_code"] = cust["country"].map(code_of)
    customers = pd.DataFrame(
        {
            "customer_id": cust["customer_id"].map(lambda i: f"C-{int(i):03d}"),
            "name": cust["company_name"],
            "country": cust["country"],
            "country_code": cust["country_code"],
            "currency": cust["currency"],
            "default_incoterm": cust["default_incoterm"],
            "payment_terms": cust["payment_terms"],
            "discount_tier": cust["discount_tier"],
            "contact_name": cust["contact_name"],
            "contact_email": [
                business_email(p, n, cc)
                for p, n, cc in zip(cust["contact_name"], cust["company_name"], cust["country_code"], strict=True)
            ],
        }
    )

    fr = t["freight_rates"].merge(t["lanes"], on="lane_id", suffixes=("", "_lane")).sort_values("freight_rate_id")
    freight = pd.DataFrame(
        {
            "freight_row_id": fr["freight_rate_id"].map(lambda i: f"FR-{int(i):03d}"),
            "origin_port": fr["origin_port"],
            "origin_port_name": fr["origin_port"].map(ORIGIN_PORTS),
            "destination_country": fr["dest_country"],
            "destination_country_code": fr["country_code"],
            "destination_port": fr["dest_port"],
            "destination_port_name": fr["dest_country"].map(lambda n: COUNTRIES[n][2]),
            "incoterm": fr["incoterm"],
            "rate_usd_per_kg": fr["rate_usd_per_kg"],
            "transit_days": fr["transit_days"].astype(int),
        }
    )

    fx = t["fx_rates"].assign(
        fx_row_id=lambda d: d["fx_id"].map(lambda i: f"FX-{int(i):02d}"), source="synthetic snapshot, not market data"
    )
    fx = fx[["fx_row_id", "snapshot_date", "base", "quote", "rate", "source"]]
    pack_table = t["packs"].drop(columns=["pack_id"])
    return {
        "products": products,
        "packs": pack_table,
        "price_list": price_list,
        "customers": customers,
        "freight_rates": freight,
        "fx_rates": fx,
    }


def check(out: dict[str, pd.DataFrame]) -> list[str]:
    """Domain laws checked here, independently of the engine's own certificate. Returns what was checked."""
    p, pl, fr, cu = out["products"], out["price_list"], out["freight_rates"], out["customers"]
    assert p["sku"].is_unique and pl["price_row_id"].is_unique and fr["freight_row_id"].is_unique
    assert set(pl["sku"]) == set(p["sku"]), "every SKU has price rows and no price row is orphaned"
    for _, g in pl.groupby(["sku", "pack_code"]):
        assert g["unit_price"].is_monotonic_decreasing and g["unit_price"].is_unique, "tier prices fall with volume"
        assert g["valid_from"].nunique() == 1 and g["valid_to"].nunique() == 1
    cost = pl["sku"].map(p.set_index("sku")["standard_cost_usd"])
    assert (pl["unit_price"] > cost).all(), "every list price is above standard cost"
    assert ((p["form"] == "liquid") == p["density_kg_per_l"].notna()).all()
    assert (pl["valid_to"] < pd.Timestamp("2026-10-01").date()).sum() > 0, (
        "some price rows have lapsed (an RFQ needs one)"
    )
    order = {"FOB": 0, "CFR": 1, "CIF": 1, "DAP": 2}
    fob = fr[fr["incoterm"] == "FOB"].groupby("origin_port")["rate_usd_per_kg"].nunique()
    assert (fob == 1).all(), "FOB handling depends on the origin port only"
    for _, g in fr.groupby(["origin_port", "destination_country"]):
        r = g.set_index("incoterm")["rate_usd_per_kg"]
        assert r["FOB"] < r["CFR"] == r["CIF"] < r["DAP"], "freight grows with the seller's obligations"
        assert set(g["incoterm"]) == set(order)
    assert set(cu["country"]) == set(COUNTRIES), "every destination country has customers"
    assert cu["name"].is_unique and cu["contact_email"].is_unique
    return [
        "unique ids",
        "every SKU priced",
        "tier prices strictly fall",
        "one validity window per offer",
        "list price above cost",
        "density exactly for liquids",
        "lapsed price rows exist",
        "freight FOB < CFR = CIF < DAP on every lane",
        "FOB handling one rate per origin port",
        "customers in every destination",
        "unique customers and emails",
    ]


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    import time

    started = time.perf_counter()
    chems = load_reference()
    bp = build_blueprint(chems)
    result = me.run("", blueprint=bp)
    if not result.passed:
        raise SystemExit(f"engine verification failed: {[f.message for f in result.verdict.findings]}")
    out = shape(result.tables)
    checked = check(out)
    files = {}
    for name, df in out.items():
        path = HERE / f"{name}.csv"
        df.to_csv(path, index=False)
        files[path.name] = {"rows": len(df), "sha256": _sha(path)}
    (HERE / "certificate.json").write_text(json.dumps(result.certificate, indent=2, default=str, sort_keys=True))
    manifest = {
        "generator": "misata_engine (Misata Studio engine) " + me.__version__,
        "route": result.route,
        "seed": SEED,
        "blueprint_hash": bp.content_hash(),
        "engine_passed": result.passed,
        "fx_snapshot_date": FX_SNAPSHOT_DATE,
        "reference": "data/reference/chemicals.yaml",
        "files": files,
        "independent_checks": checked,
    }
    (HERE / "manifest.json").write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    print(
        f"generated {sum(f['rows'] for f in files.values())} rows in {len(files)} files "
        f"({time.perf_counter() - started:.2f}s, blueprint {bp.content_hash()[:12]}, engine passed)"
    )
    for n, f in files.items():
        print(f"  {n:<20} {f['rows']:>5} rows  {f['sha256'][:12]}")


if __name__ == "__main__":
    main()
