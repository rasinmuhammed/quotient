def cas_is_valid(cas: str) -> bool:
    """CAS registry number check digit: digits before the last, weighted 1, 2, 3... from the right, sum mod 10."""
    parts = cas.split("-")
    if len(parts) != 3 or not all(p.isdigit() for p in parts) or len(parts[2]) != 1 or len(parts[1]) != 2:
        return False
    body = parts[0] + parts[1]
    return sum((i + 1) * int(d) for i, d in enumerate(reversed(body))) % 10 == int(parts[2])


def load_reference() -> list[dict]:
    chems = yaml.safe_load((HERE / "reference" / "chemicals.yaml").read_text())["chemicals"]
    grades = {g["grade"] for g in GRADES}
    owner: dict[str, str] = {}
    for c in chems:
        if not cas_is_valid(c["cas"]):
            raise ValueError(f"{c['code']}: CAS {c['cas']} fails its check digit")
        if (c["form"] == "liquid") != (c["density"] is not None):
            raise ValueError(f"{c['code']}: liquids need a density, solids must not have one")
        if not set(c["grades"]) <= grades:
            raise ValueError(f"{c['code']}: unknown grade in {c['grades']}")
        for name in [c["name"], *c["synonyms"], *c["trade_names"]]:
            key = " ".join(name.lower().split())
            if owner.setdefault(key, c["code"]) != c["code"]:
                raise ValueError(f"synonym '{name}' names both {owner[key]} and {c['code']}")
    if len({c["code"] for c in chems}) != len(chems) or len({c["cas"] for c in chems}) != len(chems):
        raise ValueError("chemical codes and CAS numbers must be unique")
    return chems


